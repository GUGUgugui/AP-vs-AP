async page => {
  if (!page.url().startsWith('http://localhost:8787/')) throw new Error('Local design audit only')
  const cdp = await page.context().newCDPSession(page)
  // Test instrumentation only: the deployed CSP is not modified.
  await cdp.send('Page.setBypassCSP', { enabled: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.context().clearCookies()
  const audits = []
  const audit = async name => {
    await page.evaluate(() => document.fonts.ready)
    if (!await page.evaluate(() => Boolean(window.axe))) await page.addScriptTag({ path: 'node_modules/axe-core/axe.min.js' })
    const data = await page.evaluate(async () => {
      const result = await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa', 'best-practice'] } })
      return { violations: result.violations.map(item => ({ id: item.id, impact: item.impact, help: item.help, nodes: item.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) })), passes: result.passes.length, incomplete: result.incomplete.map(item => ({ id: item.id, nodes: item.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) })) }
    })
    audits.push({ name, ...data })
  }
  await page.goto('http://localhost:8787/')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: '以游客身份游玩' }).waitFor()
  await audit('public-access-desktop')
  await page.setViewportSize({ width: 320, height: 760 })
  await audit('public-access-mobile')
  await page.getByRole('button', { name: '以游客身份游玩' }).click()
  await page.getByRole('button', { name: '开始匹配', exact: true }).waitFor()
  await audit('lobby-mobile')
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.locator('.badge-grid').waitFor()
  await audit('notebook-mobile')
  await page.getByRole('button', { name: '登录 / 注册' }).click()
  await page.getByRole('dialog').waitFor()
  await audit('login-dialog')
  await page.getByRole('dialog').getByRole('button', { name: '注册', exact: true }).click()
  await audit('register-dialog')
  await page.getByRole('button', { name: '取消，继续游玩' }).click()
  await page.getByRole('button', { name: '首页', exact: true }).click()
  await page.getByRole('button', { name: '开始匹配', exact: true }).click()
  await page.locator('.game-layout').waitFor({ timeout: 12000 })
  await audit('chat-initial-mobile')
  // Empty local provider key; testing these UI messages never calls DeepSeek.
  for (let index = 1; index <= 3; index++) {
    await page.getByRole('textbox', { name: '发送消息' }).fill('无障碍检查 ' + index)
    await page.waitForFunction(() => !document.querySelector('.composer-bottom button').disabled)
    await page.getByRole('textbox', { name: '发送消息' }).press('Enter')
    await page.waitForFunction(expected => document.querySelectorAll('.message-row.self').length === expected, index)
    await page.locator('.toast-notice').waitFor({ timeout: 10000 })
    await page.locator('.toast-notice').waitFor({ state: 'hidden', timeout: 10000 })
  }
  await audit('judgment-mobile')
  await page.setViewportSize({ width: 1440, height: 900 })
  await audit('judgment-desktop')
  await page.getByRole('button', { name: /^AI(?: MACHINE)?$/ }).click()
  await page.getByRole('button', { name: '提交判断 / 揭晓' }).click()
  await page.locator('.reveal-screen').waitFor()
  await audit('result-desktop')
  await page.getByRole('button', { name: '举报这段对话' }).click()
  await page.getByRole('dialog', { name: '举报对话' }).waitFor()
  await audit('report-dialog')
  await page.getByRole('button', { name: '取消，继续游玩' }).click()
  await page.goto('http://localhost:8787/admin')
  await page.locator('#admin-password').waitFor()
  await audit('admin-login')
  await page.locator('#admin-password').fill('local-qa-features')
  await page.getByRole('button', { name: '进入', exact: true }).click()
  await page.locator('.admin-primary-nav').waitFor()
  await audit('admin-live')
  await page.getByRole('button', { name: '02历史档案', exact: true }).click()
  await page.locator('.archive-list > button').first().waitFor()
  await page.locator('.archive-transcript').waitFor()
  await audit('admin-history')
  await page.getByRole('button', { name: '03运行指标', exact: true }).click()
  await page.locator('.observability-kpis').waitFor()
  await audit('admin-metrics')
  await page.getByRole('button', { name: '04反馈与训练', exact: true }).click()
  await page.locator('.community-board').first().waitFor()
  await audit('admin-community')
  await page.setViewportSize({ width: 390, height: 844 })
  await audit('admin-community-mobile')
  return { audited: audits.length, violations: audits.reduce((sum, item) => sum + item.violations.length, 0), audits }
}
